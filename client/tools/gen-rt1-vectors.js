'use strict';

/**
 * 重新生成 test/vectors/rt1-vectors.json（RT1 跨语言对拍向量）。
 *
 * 用法：node tools/gen-rt1-vectors.js
 * fr 侧 test/rt1_vectors_test.dart 内嵌同一份值，任何派生参数改动
 * （盐、info 标签、迭代次数、字母表）都必须重跑本脚本并同步 fr 测试。
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const rtCrypto = require('../lib/rt-crypto');

const KEY = 'rt1 Test-KEY ab12';
const PLAINTEXT = { text: '你好 RT1，including emoji 👨‍👩‍👧‍👦!', ts: 1730000000000 };
const PAIR_NONCE = 'a1b2c3d4e5f60718';

function build() {
  const d = rtCrypto.deriveFromKey(KEY);
  // 向量信封用固定 nonce（确定性）；真实 seal 是随机 nonce
  const nonce = Buffer.alloc(12, 7);
  const aad = rtCrypto.buildAad(d.room, 'p2c', 7);
  const cipher = crypto.createCipheriv('aes-256-gcm', d.keyPhoneToPc, nonce);
  cipher.setAAD(Buffer.from(aad, 'utf8'));
  const ct = Buffer.concat([
    cipher.update(Buffer.from(JSON.stringify(PLAINTEXT), 'utf8')),
    cipher.final(),
    cipher.getAuthTag(),
  ]);
  return {
    comment:
      'RT1 cross-language vectors; generated by mn-rt client/tools/gen-rt1-vectors.js; fr test/rt1_vectors_test.dart must agree',
    input_key: KEY,
    normalized_key: rtCrypto.normalizeKey(KEY),
    room: d.room,
    pair_salt_hex: d.pairSalt.toString('hex'),
    key_phone_to_pc_hex: d.keyPhoneToPc.toString('hex'),
    key_pc_to_phone_hex: d.keyPcToPhone.toString('hex'),
    envelope: {
      sid: 'deadbeef',
      seq: 7,
      direction: 'p2c',
      nonce: nonce.toString('base64'),
      ct: ct.toString('base64'),
    },
    envelope_plaintext: PLAINTEXT,
    pair_nonce: PAIR_NONCE,
    pair_proof_hex: rtCrypto.pairProof(d.pairSalt, PAIR_NONCE),
  };
}

if (require.main === module) {
  const out = path.join(__dirname, '..', 'test', 'vectors', 'rt1-vectors.json');
  const vec = build();
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify(vec, null, 2)}\n`, 'utf8');
  console.log(`vectors written: ${out}`);
  console.log(`room: ${vec.room}`);
}

module.exports = { build };
